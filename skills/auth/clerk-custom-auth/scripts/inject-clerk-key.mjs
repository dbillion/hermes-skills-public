// Template: build-time Clerk key injector for frontends that can't natively
// read .env.local at build (e.g. Angular). Copies into your project's
// scripts/ dir, then wire `"prebuild": "node scripts/inject-clerk-key.mjs"`.
// The GENERATED target file MUST be gitignored (see SKILL.md).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..'); // project root (script lives in scripts/)
const envLocal = join(root, '.env.local');
const target = join(root, 'src', 'environments', 'environment.ts'); // adjust per framework

function readPublishableKey() {
  if (!existsSync(envLocal)) return '';
  const m = readFileSync(envLocal, 'utf8').match(/CLERK_PUBLISHABLE_KEY=([^\s]+)/);
  return m ? m[1] : '';
}

const key = readPublishableKey();
const content = `// AUTO-GENERATED by scripts/inject-clerk-key.mjs — gitignored, DO NOT COMMIT.
// Key sourced from the gitignored .env.local at build time.
export const environment = {
  production: ${process.env.NODE_ENV === 'production' ? 'true' : 'false'},
  clerkPublishableKey: ${key ? `'${key}'` : "''"},
};
`;
writeFileSync(target, content, 'utf8');
console.log(
  key
    ? 'environment.ts generated with Clerk publishable key (from .env.local).'
    : 'WARNING: CLERK_PUBLISHABLE_KEY not found in .env.local — left empty.',
);
